CREATE TABLE auth.roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  description VARCHAR(255) NOT NULL
);
CREATE TABLE auth.permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL
);
CREATE TABLE auth.role_permissions (
  role_id BIGINT NOT NULL REFERENCES auth.roles(id),
  permission_id BIGINT NOT NULL REFERENCES auth.permissions(id),
  PRIMARY KEY(role_id, permission_id)
);
CREATE TABLE auth.users (
  id UUID PRIMARY KEY,
  first_name VARCHAR(80) NOT NULL CHECK (length(trim(first_name)) > 0),
  last_name VARCHAR(80) NOT NULL CHECK (length(trim(last_name)) > 0),
  dni VARCHAR(8) NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{8}$'),
  phone VARCHAR(20) CHECK (phone IS NULL OR phone ~ '^\+?[0-9 ()-]{6,20}$'),
  email VARCHAR(254) NOT NULL CHECK (email = lower(trim(email)) AND email LIKE '%@%'),
  password_hash VARCHAR(255) NOT NULL,
  role_id BIGINT NOT NULL REFERENCES auth.roles(id),
  branch_id UUID,
  enabled BOOLEAN NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  last_login_at TIMESTAMPTZ,
  version BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_users_email_ci ON auth.users(lower(email));
CREATE INDEX ix_users_role_status ON auth.users(role_id, enabled);
CREATE TABLE auth.refresh_sessions (
  id UUID PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id),
  family_id UUID NOT NULL,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at > created_at),
  revoked_at TIMESTAMPTZ,
  replaced_by UUID REFERENCES auth.refresh_sessions(id)
);
CREATE INDEX ix_refresh_user ON auth.refresh_sessions(user_id);
CREATE INDEX ix_refresh_family ON auth.refresh_sessions(family_id);
CREATE TABLE auth.security_lock (id INTEGER PRIMARY KEY CHECK(id = 1));
