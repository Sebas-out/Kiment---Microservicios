import { test } from 'node:test';
import assert from 'node:assert/strict';
import { sourceModule } from './users-test-loader.mjs';
const b=await import(await sourceModule('src/features/branches/contracts.ts'));
const o=await import(await sourceModule('src/features/users/operations.ts'));
const create={code:'TEST-01',name:'Sucursal aislada',branchType:'MIXTO',enabled:true,city:'Lima',ubigeo:'010101',email:'local@example.invalid',sunatCode:'0001'};
const branch={...create,id:'521c9f1d-624d-4fe5-8c70-9b43396059b2',address:'Dirección',phone:'010000000',createdAt:'2026-11-04T00:00:00Z',updatedAt:'2026-11-04T00:00:00Z'};
test('V5 creation requires a real enum and accepts the five optional fields',()=>{
  assert.equal(b.branchCreateSchema.safeParse(create).success,true);
  for(const branchType of [undefined,null,'','TIENDA'])assert.equal(b.branchCreateSchema.safeParse({...create,branchType}).success,false);
  for(const branchType of ['VENTA','ALMACEN','MIXTO'])assert.equal(b.branchCreateSchema.safeParse({...create,branchType}).success,true);
});
test('ubigeo remains six string digits including leading zeroes',()=>{
  assert.equal(b.branchCreateSchema.parse({...create,ubigeo:'000001'}).ubigeo,'000001');
  for(const ubigeo of ['12345','1234567','150a01',123456])assert.equal(b.branchCreateSchema.safeParse({...create,ubigeo}).success,false);
});
test('SUNAT remains four string digits and is never autogenerated',()=>{
  assert.equal(b.branchCreateSchema.parse({...create,sunatCode:'0000'}).sunatCode,'0000');
  for(const sunatCode of ['123','12345','A001',1])assert.equal(b.branchCreateSchema.safeParse({...create,sunatCode}).success,false);
  const {sunatCode,...without}=create;assert.equal(b.branchCreateSchema.parse(without).sunatCode,undefined);
});
test('optional fields can be omitted, null or cleared with empty/whitespace strings',()=>{
  const result=b.branchEditSchema.parse({city:'  ',ubigeo:' ',sunatCode:' ',email:'  ',address:' ',phone:' '});
  assert.deepEqual(result,{city:'',ubigeo:'',sunatCode:'',email:'',address:'',phone:''});
  assert.deepEqual(b.branchEditSchema.parse({city:null,branchType:null}),{city:null,branchType:null});
});
test('email and city use exact backend limits',()=>{
  assert.equal(b.branchCreateSchema.safeParse({...create,city:'a'.repeat(101)}).success,false);
  assert.equal(b.branchCreateSchema.safeParse({...create,email:'invalid'}).success,false);
  assert.equal(b.branchCreateSchema.safeParse({...create,email:'a'.repeat(140)+'@example.com'}).success,false);
  assert.equal(b.branchCreateSchema.safeParse({...create,email:'',city:''}).success,true);
});
test('legacy null type stays unclassified until explicitly changed',()=>{
  const legacy=b.branchSchema.parse({...branch,branchType:null});
  assert.equal(b.branchDefaults(legacy).branchType,'');
  assert.deepEqual(b.buildBranchPatch(b.branchDefaults(legacy),legacy),{});
  assert.deepEqual(b.buildBranchPatch({...b.branchDefaults(legacy),branchType:'ALMACEN'},legacy),{branchType:'ALMACEN'});
});
test('editing a field omits unrelated data and cannot erase concurrent updates',()=>{
  assert.deepEqual(b.buildBranchPatch({...b.branchDefaults(branch),name:'Otro nombre'},branch),{name:'Otro nombre'});
  assert.deepEqual(b.buildBranchPatch({...b.branchDefaults(branch),city:''},branch),{city:''});
  assert.deepEqual(b.buildBranchPatch({...b.branchDefaults(branch),code:'DIFFERENT',enabled:false},branch),{});
});
test('all unknown fiscal fields and status/code changes are rejected by details PATCH',()=>{
  for(const value of [{companyId:branch.id},{ruc:'12345678901'},{enabled:false},{code:'NEW'},{branchType:''}])assert.equal(b.branchEditSchema.safeParse(value).success,false);
});
test('V5 filters use type, city and sunatCode with their actual controller names',()=>{
  const op=o.operation('GET',['branches'],new URLSearchParams('type=MIXTO&city=Lima&sunatCode=0001'));
  assert.ok(op.path.includes('type=MIXTO'));assert.ok(op.path.includes('sunatCode=0001'));
  assert.equal(b.branchQuerySchema.safeParse({branchType:'MIXTO'}).success,false);
});
test('duplicate SUNAT and V5 field errors remain understandable and sanitized',()=>{
  const detail='El código de establecimiento SUNAT ya está registrado';
  assert.equal(o.backendProblem(409,{detail}).error,detail);
  const problem=o.backendProblem(400,{errors:[{field:'ubigeo',message:'private input'},{field:'sunatCode',message:'private input'}]});
  assert.ok(problem.fields.ubigeo);assert.ok(problem.fields.sunatCode);assert.ok(!JSON.stringify(problem).includes('private input'));
});
